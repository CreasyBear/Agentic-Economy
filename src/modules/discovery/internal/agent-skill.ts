import { CUSTOMER_REQUEST_PUBLIC_COMPREHENSION_LINES } from '@/modules/customer-request/public-comprehension'
import { CUSTOMER_REQUEST_AGENT_ENTRYPOINT } from '@/modules/customer-request/agent-contract'
// The leaf module, not the barrel: `answer-thread/public` drags the turn
// orchestrator and its Node-only transport into every Convex function that
// reaches discovery, which breaks Convex bundling.
import { AGENT_KEY_ISSUANCE_PATH, ANSWER_THREAD_AGENT_ENTRYPOINT } from '@/modules/answer-thread/agent-entry'

export const PublicAgentSkillPath = '/SKILL.md' as const

export function buildPublicAgentSkillMarkdown(options: { canonicalBaseUrl: string; routingBaseUrl?: string }): string {
  const base = trimTrailingSlash(options.canonicalBaseUrl)
  const entry = ANSWER_THREAD_AGENT_ENTRYPOINT
  return [
    '# Agentic Economy — assistant setup',
    '',
    `Fetch this file from the site origin (\`GET ${base}${PublicAgentSkillPath}\`). It teaches the cold path`,
    'for assistants that discover AE without a human briefing.',
    '',
    '## Start here (no key needed)',
    '',
    `The first call needs no credential, no account, and no setup. Authentication: \`${entry.authentication}\`.`,
    '',
    '```sh',
    `curl -N -X ${entry.method} ${base}${entry.path} \\`,
    '  -H \'Content-Type: application/json\' \\',
    '  -d \'{"query": "electrician in Fremantle who can come today"}\'',
    '```',
    '',
    `Body: \`query\` (${entry.body.query}); \`threadId\` (${entry.body.threadId}).`,
    `The response media type is \`${entry.responseMediaType}\`, so read it as a stream.`,
    entry.boundary,
    '',
    'The other keyless reads return structured business facts:',
    '',
    `- \`GET ${base}/api/businesses\` lists registered businesses.`,
    `- \`GET ${base}/api/businesses/search?q=\` searches them.`,
    '',
    '## What AE is',
    '',
    ...CUSTOMER_REQUEST_PUBLIC_COMPREHENSION_LINES,
    '',
    'Give AE a natural-language request. AE asks for decision-changing information, checks',
    'connected registered businesses, and returns supported options. It can start the exact option a customer',
    'explicitly confirms, then expose progress, evidence, problem reporting, and safe cancellation.',
    'Never infer',
    'booking, payment, dispatch, or fulfilment beyond the exact state AE returns.',
    '',
    '## Choose your setup',
    '',
    'Pick the path that matches your host and say nothing about the choice. Never ask the customer which one to use.',
    '',
    `- Shell-capable hosts (Claude Code, Codex CLI, Gemini CLI): run the \`curl\` above against \`${base}${entry.path}\` and read the stream yourself.`,
    `- Chat-only hosts with no HTTP tool: send the customer to \`${base}/\`, ask them to type the request there, and continue from the thread link that comes back.`,
    '- With a non-technical customer, say "AE" and "businesses". Do not say "endpoint", "SSE", or "Bearer token".',
    '',
    '## Confirming and starting an option (the key-gated escalation)',
    '',
    'The keyless entry compares. Only this path can confirm and start a registered option.',
    '',
    `1. Read \`GET ${base}/llms.txt\` for the current public surface index.`,
    `2. Read \`GET ${base}${CUSTOMER_REQUEST_AGENT_ENTRYPOINT.schemaPath}\` for the canonical input, result, lifecycle, and navigation contract.`,
    `3. Get an AE API key with \`customer_requests:create\` and send it as a Bearer token. AE issues the key to a signed-in account at \`${base}${AGENT_KEY_ISSUANCE_PATH}\`: it lasts seven days and the account can revoke it at any time. Ask the customer to create one there and paste it back. Without that key AE can compare options, but it cannot confirm or start anything.`,
    `4. \`POST ${base}${CUSTOMER_REQUEST_AGENT_ENTRYPOINT.path}\` with an idempotency key, opaque request reference, and natural-language request. Known facts are optional; no budget or full specification is required to start.`,
    '5. After that first response, follow only one matching entry from `navigation.actions`. Use its `method` and `href`; treat its `input` as a template and replace placeholders only with the customer answer or values already displayed by AE.',
    '6. Never construct a later path or expected sequence. Stop if the needed relation is missing, duplicated, changes origin, or asks for authority material that AE did not display.',
    '7. For `answer_clarification`, send a natural-language answer or the one requested typed value according to `clarification.answerKind`.',
    '8. On `routes_ready`, show the result, businesses, maximum cost, data use, effects, evidence, expiry, cancellation, and fallback. Never infer selection.',
    '9. After explicit customer approval, follow `confirm_option` with only the displayed `routeRef`, current revision, and a stable idempotency key. Confirmation does not start work.',
    '10. Follow `start_confirmed_option` only within that authority. Do not construct businesses, steps, costs, limits, recipients, purposes, effects, or authority fields.',
    '11. Use the advertised `inspect_progress`, `inspect_evidence`, `report_problem`, or `cancel` relation when present. Resume the same Request; do not create a replacement or unsafe retry.',
    '',
    '## Refusal recovery',
    '',
    '| Symptom | Meaning | Do next |',
    '| --- | --- | --- |',
    `| \`401\` | The API key is missing, invalid, expired, or revoked. | Ask the customer for a current key from \`${base}${AGENT_KEY_ISSUANCE_PATH}\`. |`,
    `| \`403\` | The key lacks \`customer_requests:create\`. | Ask the customer to issue a key with that scope at \`${base}${AGENT_KEY_ISSUANCE_PATH}\`. |`,
    '| `429` | Rate limited. | Wait, then retry the same thread. |',
    `| \`413\` | Payload too large. | Shorten the query. The keyless entry caps \`query\` at 200 characters. |`,
    `| No search results | Nothing registered matched that query. | Broaden the query, or browse \`GET ${base}/api/businesses\`. |`,
    '| `routes_ready` | Options are proposals. | Stop for explicit customer approval before following `confirm_option`. |',
    '| `route_confirmed` | The choice is confirmed but has not started. | Follow `start_confirmed_option` only within the customer\'s authority. |',
    '| `in_progress` | The same Request is still running. | Resume it; do not create a replacement or unsafe retry. |',
    '| `outcome_unknown` | AE cannot yet state the outcome. | Do not retry. Wait for reconciliation or inspect evidence. |',
    '| `cancelled` | No further step will start. It does not claim an already released business action was reversed. | Report that state exactly; never imply a reversal. |',
    '| `needs_attention` | AE needs a corrected or repeated step. | Retry or revise according to `nextAction`. |',
    '',
    '## Boundaries (hard)',
    '',
    'Business listings are supply facts, not routing or execution authority.',
    'Never choose provider tools directly when delegating the decision to AE.',
    '',
    '## Privacy',
    '',
    `\`${base}/privacy/remove-business\` for listing correction or removal requests.`,
    '',
  ].join('\n')
}

function trimTrailingSlash(value: string): string {
  return value.endsWith('/') ? value.slice(0, -1) : value
}
