import { CUSTOMER_REQUEST_MACHINE_COMPREHENSION_LINES } from '@/modules/customer-request/public-comprehension'
import {
  CUSTOMER_REQUEST_AGENT_ENTRYPOINT,
  CUSTOMER_REQUEST_AGENT_SCOPE,
  CUSTOMER_REQUEST_AUTHORITY_MODE_VALUES,
} from '@/modules/customer-request/agent-contract'
// The leaf module, not the barrel: `answer-thread/public` drags the turn
// orchestrator and its Node-only transport into every Convex function that
// reaches discovery, which breaks Convex bundling.
import { AGENT_KEY_ISSUANCE_PATH, ANSWER_THREAD_AGENT_ENTRYPOINT } from '@/modules/answer-thread/agent-entry'

export const PublicAgentSkillPath = '/SKILL.md' as const

export function buildPublicAgentSkillMarkdown(options: {
  canonicalBaseUrl: string
  routingBaseUrl?: string
  mcpToolNames: readonly string[]
}): string {
  const base = trimTrailingSlash(options.canonicalBaseUrl)
  const entry = ANSWER_THREAD_AGENT_ENTRYPOINT
  return [
    '# Agentic Economy — assistant setup',
    '',
    `Fetch this file from the site origin (\`GET ${base}${PublicAgentSkillPath}\`). It teaches the cold path`,
    'for assistants that discover AE without a human briefing.',
    '',
    '## Start here (no key needed)',
    '',
    `The first call needs no credential, no account, and no setup. Authentication: \`${entry.authentication}\`.`,
    'Your assistant can use this market directly: reads are free and keyless, so no account is needed to compare published options.',
    '',
    '```sh',
    `curl -N -X ${entry.method} ${base}${entry.path} \\`,
    '  -H \'Content-Type: application/json\' \\',
    '  -d \'{"query": "electrician in Fremantle who can come today"}\'',
    '```',
    '',
    `Body: \`query\` (${entry.body.query}); \`threadId\` (${entry.body.threadId}).`,
    `The response media type is \`${entry.responseMediaType}\`, so read it as a stream.`,
    entry.boundary,
    '',
    'The other keyless reads return structured business facts:',
    '',
    `- \`GET ${base}/api/businesses\` lists registered businesses.`,
    `- \`GET ${base}/api/businesses/search?q=\` searches them.`,
    '',
    '## Services API',
    '',
    'These routes are keyless:',
    `- \`GET /api/v1/services\` (${base}/api/v1/services) returns ONE PAGE of published services. Each service uses \`summary\`, \`pricingSummary\`, and \`price\` fields, with endpoints carrying method, URL, summary, pricing summary, and publication provenance.`,
    `- \`GET /api/v1/services/search?q={query}\` (${base}/api/v1/services/search?q={query}) returns ONE PAGE of matching services.`,
    '- Follow `pagination.nextCursor` and request another page while `pagination.hasMore` is true.',
    '- Endpoint metadata keeps its publication provenance (`business_declared` or `publicly_observed`). The QUOTE RESPONSE carries `provenance: ae_sandbox_provider`.',
    '- Endpoints marked `access: \'open\'` are callable without an account or API key.',
    '- Open endpoints are currently served by AE\'s labelled sandbox provider. They do not promise real-provider fulfilment or settlement.',
    `- Example: POST /api/sandbox/adelaide-dental-clinic/checkup-quote (${base}/api/sandbox/adelaide-dental-clinic/checkup-quote) returns a priced, time-bounded quote JSON.`,
    '',
    'Keyless service flow:',
    '1. Discover services.',
    '2. Follow `pagination.nextCursor` while `pagination.hasMore` is true.',
    '3. Search with `GET /api/v1/services/search?q={query}` when needed.',
    '4. Pick a service from the response.',
    '5. Call an endpoint only when its `access: \'open\'`.',
    '',
    '## MCP server',
    '',
    `Endpoint: \`${base}/mcp\` (Streamable HTTP, keyless).`,
    '',
    'Install:',
    '```sh',
    `claude mcp add --transport http agentic-economy ${base}/mcp`,
    `codex mcp add agentic-economy --url ${base}/mcp`,
    '```',
    '',
    'Tools:',
    ...options.mcpToolNames.map((toolName) => `- \`${toolName}\``),
    '',
    'All tools are read-only; none books, charges, dispatches, or sends an inquiry.',
    '',
    '## What AE is',
    '',
    ...CUSTOMER_REQUEST_MACHINE_COMPREHENSION_LINES,
    '',
    'Give AE a natural-language request. AE asks for decision-changing information, checks',
    'connected registered businesses, and returns supported options. It can start the exact option a customer',
    'explicitly confirms, then expose progress, evidence, problem reporting, and safe cancellation.',
    'Never infer',
    'booking, payment, dispatch, or fulfilment beyond the exact state AE returns.',
    '',
    '## Choose your setup',
    '',
    'Pick the path that matches your host and say nothing about the choice. Never ask the customer which one to use.',
    '',
    `- Shell-capable hosts (Claude Code, Codex CLI, Gemini CLI): run the \`curl\` above against \`${base}${entry.path}\` and read the stream yourself.`,
    `- Chat-only hosts with no HTTP tool: send the customer to \`${base}/\`, ask them to type the request there, and continue from the thread link that comes back.`,
    '- With a non-technical customer, say "AE" and "businesses". Do not say "endpoint", "SSE", or "Bearer token".',
    '',
    '## Confirming and starting an option (the key-gated escalation)',
    '',
    `3. Request a scoped credential with \`POST ${base}/oauth/device_authorization\` using \`${CUSTOMER_REQUEST_AGENT_SCOPE}\` and one exact mode (\`${CUSTOMER_REQUEST_AUTHORITY_MODE_VALUES.join('`, `')}\`). Show \`verification_uri\` and \`user_code\` to the signed-in owner; the owner approves at \`${base}${AGENT_KEY_ISSUANCE_PATH}/authorize?user_code=...\`. Poll \`POST ${base}/oauth/token\` at the returned interval. Send the returned bearer key (valid for seven days) only to \`${base}${CUSTOMER_REQUEST_AGENT_ENTRYPOINT.path}\`; never paste secrets.`,
    'Without that key AE can compare options, but it cannot confirm or start anything.',
    '',
    `1. Read \`GET ${base}/llms.txt\` for the current public surface index.`,
    `4. \`POST ${base}${CUSTOMER_REQUEST_AGENT_ENTRYPOINT.path}\` with an idempotency key, requestRef, and natural-language request.`,
    '5. Follow only one matching `navigation.actions` relation and its displayed input template.',
    '6. Never construct a later path, sequence, business, limit, recipient, effect, or authority field.',
    '7. Answer clarification only with the customer answer or displayed typed value.',
    '8. On `routes_ready`, show options, costs, data use, effects, evidence, expiry, cancellation, and fallback; never infer selection.',
    '9. After explicit approval, follow `confirm_option` with displayed routeRef, revision, and idempotency key.',
    '10. Follow `start_confirmed_option` only within displayed authority; use progress, evidence, problem, or cancel relations.',
    '',
    '## Refusal recovery',
    '',
    '| Symptom | Meaning | Do next |',
    '| --- | --- | --- |',
    `| \`401\` | The bearer key is missing, invalid, expired, or revoked. | Restart \`POST ${base}/oauth/device_authorization\`; show the new \`verification_uri\` and \`user_code\` to the signed-in owner. |`,
    '| `429` | Rate limited. | Wait, then retry the same thread. |',
    `| \`403\` | The key lacks the required \`${CUSTOMER_REQUEST_AGENT_SCOPE}\` or mode ceiling. | Restart authorization and request the exact narrower mode needed. |`,
    `| \`413\` | Payload too large. | Shorten the query. The keyless entry caps \`query\` at 200 characters. |`,
    `| No search results | Nothing registered matched that query. | Broaden the query, or browse \`GET ${base}/api/businesses\`. |`,
    '| `routes_ready` | Options are proposals. | Stop for explicit customer approval before following `confirm_option`. |',
    '| `route_confirmed` | The choice is confirmed but has not started. | Follow `start_confirmed_option` only within the customer\'s authority. |',
    '| `in_progress` | The same Request is still running. | Resume it; do not create a replacement or unsafe retry. |',
    '| `outcome_unknown` | AE cannot yet state the outcome. | Do not retry. Wait for reconciliation or inspect evidence. |',
    '| `cancelled` | No further step will start. It does not claim an already released business action was reversed. | Report that state exactly; never imply a reversal. |',
    '| `needs_attention` | AE needs a corrected or repeated step. | Retry or revise according to `nextAction`. |',
    '',
    '## Boundaries (hard)',
    '',
    'Business listings are supply facts, not routing or execution authority.',
    'Never choose provider tools directly when delegating the decision to AE.',
    '',
    '## Privacy',
    '',
    `\`${base}/privacy/remove-business\` for listing correction or removal requests.`,
    '',
  ].join('\n')
}

function trimTrailingSlash(value: string): string {
  return value.endsWith('/') ? value.slice(0, -1) : value
}
