export function buildPublicAgentSkillMarkdown(options: { canonicalBaseUrl: string; routingBaseUrl?: string }): string {
  const base = trimTrailingSlash(options.canonicalBaseUrl)
  return [
    '# Agentic Economy — assistant setup',
    '',
    `Fetch this file from the site origin (\`GET ${base}/SKILL.md\`). It teaches the cold path`,
    'for assistants that discover AE without a human briefing.',
    '',
    '## What AE is',
    '',
    'Give AE a natural-language request. AE asks for decision-changing information, checks',
    'connected registered businesses, and returns supported options. It can start the exact option a customer',
    'explicitly confirms, then expose progress, evidence, problem reporting, and safe cancellation. Never infer',
    'booking, payment, dispatch, or fulfilment beyond the exact state AE returns.',
    '',
    '## Request sequence (do this in order)',
    '',
    `1. Read \`GET ${base}/llms.txt\` for the current public surface index.`,
    '2. Obtain an AE API key with `customer_requests:create` and send it as a Bearer token.',
    `3. \`POST ${base}/api/v1/requests\` with an idempotency key, opaque request reference, and natural-language request. Known facts are optional; no budget or full specification is required to start.`,
    '4. Follow `clarification.answerKind`: send natural-language answers to `/messages`; send only requested typed values to `/facts`.',
    '5. To compare, POST `/api/v1/requests/:requestRef/options` with the current revision and a new idempotency key.',
    '6. On `routes_ready`, show the customer-facing result, businesses, maximum cost, data use, effects, evidence, expiry, cancellation, and fallback. Never infer selection.',
    '7. After explicit customer approval, POST only the displayed `routeRef`, current revision, and a stable idempotency key to `/confirmation`. Confirmation does not start work.',
    '8. POST a stable idempotency key to `/run` to start or safely resume. Do not construct businesses, steps, costs, limits, recipients, or authority fields.',
    '9. Resume with `GET /api/v1/requests/:requestRef`. Follow `nextAction` and `activity.safeNextAction`.',
    '10. Inspect observed receipts with `/evidence`, report a problem with `/problems`, and use `/cancellation` only while AE says stopping remains available.',
    '',
    `Browse without a search query: \`GET ${base}/api/businesses\` (list) or`,
    `\`GET ${base}/api/businesses/search?q=\`.`,
    '',
    '## Refusal recovery',
    '',
    '- `401` means the API key is missing, invalid, expired, or revoked.',
    '- `403` means the key lacks `customer_requests:create`.',
    '- `routes_ready` means options are proposals. Stop for explicit customer approval before `/confirmation`.',
    '- `route_confirmed` means the choice is confirmed but has not started. Call `/run` only within the customer\'s authority.',
    '- `in_progress` means resume the same Request; do not create a replacement or unsafe retry.',
    '- `outcome_unknown` means do not retry. Wait for reconciliation or inspect evidence.',
    '- `cancelled` means no further step will start; it does not claim an already released business action was reversed.',
    '- `needs_attention` means retry or revise according to `nextAction`.',
    '',
    '## Boundaries (hard)',
    '',
    'Business listings are supply facts, not routing or execution authority.',
    'Never choose provider tools directly when delegating the decision to AE.',
    '',
    '## Privacy',
    '',
    `\`${base}/privacy/remove-business\` for listing correction or removal requests.`,
    '',
  ].join('\n')
}

function trimTrailingSlash(value: string): string {
  return value.endsWith('/') ? value.slice(0, -1) : value
}
